require 'CommonClasses/BaseModel'

module MobiSys
	
	class PolicyPaymentModel < BaseModel

		def initialize(io)
			#puts "~~~in PolicyPaymentModel initialize: #{io.inspect}"
			super(io)
			#puts "~~~baseIO:#{self.baseIO}"
		end

		def getModel
			#logInfo("~~~baseIO in PolicyPaymentModel:#{self.baseIO.inspect}")
			#logInfo("~~~in self.parentBaseDO : #{self.parentBaseDO.class.name}")
			policyPayment = self.parentBaseDO.getPolicyPayment(self.paymentInstructionTypeCd)
			if policyPayment == nil and self.createNewObject
				policyPayment = PolicyPayment.new(:paymentInstructionTypeCd => self.paymentInstructionTypeCd)
				self.parentBaseDO.addPolicyPayment(policyPayment)
			end
			#If payer doesn't exist then set it to PROPOSER by default
			policyPayment.payerTypeCd = "PROPOSER" if policyPayment && policyPayment.payerTypeCd.to_s == ""
			
			return policyPayment 
		end

		def setModel(entity)
			if entity 
				policy = self.parentBaseDO
				payerParty = policy.getPayerParty(self.paymentInstructionTypeCd)
				policyPartyRole = policy.getPayerPartyRole(self.paymentInstructionTypeCd)
				entity.payerPartyRefGuid = payerParty.guid if payerParty != nil

				if entity.payerTypeCd.to_s == "SUPPLEMENTARY"
					#If there is 1 supplementary, set that as payerPartyRefGuid
					suppPartyList = policy.getPartyList("SUPPLEMENTARY")
					entity.payerPartyRefGuid = suppPartyList.first.guid if suppPartyList.size == 1
					if entity.payerPartyRefGuid.to_s != ""
	                    #If Db Party has partySameAsCd as OTHER, remove from Db
	                    if payerParty != nil and policyPartyRole != nil and policyPartyRole.partySameAsCd.to_s == "OTHER"
		                    payerParty.removed = "YES"
		                    @baseIO.additionalData = {} if (@baseIO.additionalData == nil || (@baseIO.additionalData != nil and !@baseIO.additionalData.is_a?(Hash)))
		                    @baseIO.additionalData["ISPARTYFINANCIALREFCHANGE"] = "YES"
		                end
	                    #Set same partyRefGuid in policyPartyRole
	                    updatedParty = policy.getPartyByGuid(entity.payerPartyRefGuid)
	                    if updatedParty
	                    	if policyPartyRole != nil
	                        	policyPartyRole.refGuid = updatedParty.guid
	                        	policyPartyRole.status = ""
	                        end
	                        entity.payerPartyRefGuid = updatedParty.guid
	                    end
	                end
				elsif entity.payerTypeCd.to_s != "OTHER"
					#If Db Party has partySameAsCd as OTHER, remove from Db
					if payerParty != nil  and policyPartyRole != nil and (policyPartyRole.partySameAsCd.to_s == "" || policyPartyRole.partySameAsCd.to_s == "OTHER")
                    	payerParty.removed = "YES"
                    	@baseIO.additionalData = {} if (@baseIO.additionalData == nil || (@baseIO.additionalData != nil and !@baseIO.additionalData.is_a?(Hash)))
	                    @baseIO.additionalData["ISPARTYFINANCIALREFCHANGE"] = "YES"
                    end
                    updatedParty = policy.getParty(entity.payerTypeCd)
                    #This nil check is required for refund case, refund party role is not generated by PolicyPartyModel.
                    if policyPartyRole == nil
                    	policyPartyRole = PolicyPartyRole.new(:roleCd => "PAYER", :paymentInstructionTypeCd => self.paymentInstructionTypeCd)
                    	policy.addPolicyPartyRole(policyPartyRole)
                    end
                    if updatedParty != nil
                        policyPartyRole.refGuid = updatedParty.guid
                        policyPartyRole.status = ""
                        entity.payerPartyRefGuid = updatedParty.guid
                    end
                end

				#In case of SAMEAS, remove partyFinancialAccount details from SAMEAS Party
				if(entity.paymentInstructionTypeCd.to_s == "RENEWALPREMIUM" and policyPartyRole != nil and policyPartyRole.partySameAsCd.to_s != "" and policyPartyRole.partySameAsCd.to_s != "OTHER" and entity.payerTypeCd != policyPartyRole.partySameAsCd)
					party = policy.getParty(policyPartyRole.partySameAsCd)
					# removed specified PartyFinancialAccountDO record.solved issue of deleting refund party financial record.
                    partyFinancialAccountToBeDelete = party.PartyFinancialAccountList.find do |partyFinancialAccount|
					  entity.partyFinAccountSeq.to_s != "" && partyFinancialAccount.partyFinancialAccountSeq.to_s != "" && entity.partyFinAccountSeq.to_i == partyFinancialAccount.partyFinancialAccountSeq.to_i
					end
                    party.removePartyFinancialAccount(partyFinancialAccountToBeDelete) if partyFinancialAccountToBeDelete.to_s != ""
					@baseIO.additionalData = {} if (@baseIO.additionalData == nil || (@baseIO.additionalData != nil and !@baseIO.additionalData.is_a?(Hash)))
			        @baseIO.additionalData["ISPARTYFINANCIALREFCHANGE"] = "YES"
				end
				
				if policyPartyRole != nil
                    policyPartyRole.partySameAsCd = entity.payerTypeCd
                    #If party changed to OTHER do not delete the party record
                    payerParty.removed = "" if payerParty != nil and entity.payerTypeCd.to_s == "OTHER"
                end
                entity.paymentInstructionTypeCd = self.paymentInstructionTypeCd
			end

			return entity
		end

	end
end

