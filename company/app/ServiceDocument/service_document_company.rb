        documentCategoryMaster = DocumentCategory.find(:first, :conditions=>{'categoryCd'=>self.docCategoryCd.to_s})
        if documentCategoryMaster
            self.entityDesc = MobiSys::BrowserHelper.getLabel(documentCategoryMaster.categoryDesc.to_s)
        else
            self.entityDesc = MobiSys::BrowserHelper.getLabel(self.docCategoryCd.to_s)
        end
    end
    
     
