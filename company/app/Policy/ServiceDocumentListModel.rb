require 'CommonClasses/BaseModel'

module MobiSys
    
    class ServiceDocumentListModel < BaseModel

        def initialize(io)
            #puts "~~~in ServiceDocumentListModel initialize: #{io.inspect}"
            super(io)
            #puts "~~~baseIO:#{self.baseIO}"
        end

        def getModel
            #logInfo("~~~baseIO in ServiceDocumentListModel:#{self.baseIO.inspect}")
            #logInfo("~~~in self.parentBaseDO : #{self.parentBaseDO.class.name}")
            partyDocumentList = []
            documentContainer = DocumentContainer.loadObject(
                :first,
                :conditions=>{
                    {:name=>'entityGuid'}=> self.parentBaseDO.docPartyGuid,
                    {:name=>'policyGuid'}=> @baseIO.baseDO.guid
                },
                :op => 'AND'
            )
            if documentContainer
                ocrReqd = ($rhoconfig[:ocr_enabled].value.to_s == "YES" ? true : false)
                partyDocumentList = documentContainer.ServiceDocumentList.select { |serviceDoc| serviceDoc.docCategoryCd == self.parentBaseDO.docCategoryCd }
                partyDocumentList.each do|partydoc|
                    imageList = Image.loadObject(
                        :all,
                        :conditions=>{
                            {:name=>'parentRefGuid'}=> partydoc.guid
                        })

                    if(imageList.size > 0 && partydoc.documentCd.to_s != "")
                        partydoc.imageCount = imageList.size
                        partydoc.acceptanceStatusCd = "FULFILLED"
                    end
                  
                    if ocrReqd
                        document = Document.find(:first, :conditions=>{'documentCd'=> partydoc.documentCd})
                        partydoc.ocrCheckReqd = "YES" if(document != nil and document.ocrIdentifier.to_s != "")
                    end
                end
            end
            if partyDocumentList.empty?
                if @baseIO.additionalData != nil and @baseIO.additionalData.has_key?("ServiceDocumentList")
                    @baseIO.additionalData["ServiceDocumentList"].each do |docCategory|
                        partyDocumentList = docCategory[self.parentBaseDO.docCategoryCd.to_s] if docCategory.keys.first == self.parentBaseDO.docCategoryCd
                    end
                else
                    partyDocumentList = MobiSys::PolicyService.createServiceDocument(self.parentBaseDO.docPartyGuid, self.parentBaseDO.docCategoryCd)
                end
            else
                    partyDocumentList = MobiSys::PolicyService.createServiceDocument(self.parentBaseDO.docPartyGuid, self.parentBaseDO.docCategoryCd, partyDocumentList)
            end

            return partyDocumentList
        end

        def setModel(entity)
            if entity && entity.size > 0
                documentContainer = DocumentContainer.loadObject(
                    :first,
                    :conditions=>{
                        {:name=>'entityGuid'}=> self.parentBaseDO.docPartyGuid,
                        {:name=>'policyGuid'}=> @baseIO.baseDO.guid
                    },
                    :op => 'AND'
                )

                if documentContainer == nil
                    documentContainer = DocumentContainer.new(
                            :entityGuid => self.parentBaseDO.docPartyGuid,
                            :entityTypeCd => 'Party',
                            :policyGuid => @baseIO.baseDO.guid
                        )
                end

                facetObj = $rhoconfig[:multiDocMode]
                multiDocMode = (facetObj && facetObj.actionValue.to_s == 'YES'? true : false) 

                entity.each do |document|
                    if document
                        if multiDocMode
                            if document.selected.to_s != 'YES' && document.isAutoGeneratedFl != "YES_UW"
                                document.removed = 'YES'
                                images = Image.loadObject(:all, :conditions => { :parentRefGuid => document.guid })
                                images.each do |img|
                                    File.delete(img.OfflineFileList[0].fileLocation) if File.exist?(img.OfflineFileList[0].fileLocation)
                                    img.OfflineFileList[0].destroy
                                    img.destroy  
                                end
                                document.imageCount = 0
                            else
                                document.receivedDt = getDBDate(document.receivedDt) if document.receivedDt
                            end
                        else
                            if document.documentCd.to_s == '' && document.isAutoGeneratedFl != "YES_UW"
                                document.removed = 'YES'
                            else
                                document.receivedDt = getDBDate(document.receivedDt) if document.receivedDt
                            end
                        end
                        document.partyGuid = self.parentBaseDO.docPartyGuid if document.partyGuid.to_s == ""
                        documentContainer.addServiceDocument(document)
                    end
                end
                documentContainer.persistAll if $isSaveAction
            end

            return entity
        end

    end
end

